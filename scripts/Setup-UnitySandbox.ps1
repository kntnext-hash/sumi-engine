[CmdletBinding()]
param([Parameter(Mandatory = $true)][string]$UnityEditor)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$editor = (Resolve-Path -LiteralPath $UnityEditor).Path
$version = (Get-Item -LiteralPath $editor).VersionInfo.ProductVersion
if ($version -notmatch '^6000\.3\.\d+[fp]\d+') { throw "Unity 6.3 LTS (6000.3.x final/patch) required; executable reports '$version'." }
$exactVersion = $Matches[0]
$project = Join-Path $repo 'UnitySandbox'
$logs = Join-Path $repo 'logs'
New-Item -ItemType Directory -Force -Path $logs | Out-Null
function Invoke-Unity([string[]]$Arguments) {
    $process = Start-Process -FilePath $editor -ArgumentList $Arguments -Wait -PassThru -WindowStyle Hidden
    if ($process.ExitCode -ne 0) { throw "Unity exited with code $($process.ExitCode). Inspect logs; do not mark setup complete." }
}
if (Test-Path -LiteralPath (Join-Path $project 'Temp/UnityLockfile')) { throw 'Close UnitySandbox in Unity before synchronizing.' }
$projectVersion = Join-Path $project 'ProjectSettings/ProjectVersion.txt'
if (Test-Path -LiteralPath $project) {
    if (!(Test-Path -LiteralPath $projectVersion)) { throw 'Existing UnitySandbox is not a verified Unity project. Preserve and inspect it before retrying.' }
    if ((Get-Content -LiteralPath $projectVersion -Raw) -notmatch "(?m)^m_EditorVersion: $([regex]::Escape($exactVersion))\s*$") { throw 'Installed Editor and existing project version differ. No automatic upgrade is performed.' }
} else {
    Invoke-Unity @('-batchmode', '-nographics', '-quit', '-createProject', "`"$project`"", '-logFile', "`"$(Join-Path $logs 'unity-create.log')`"")
    if (!(Test-Path -LiteralPath $projectVersion)) { throw 'Unity did not create ProjectVersion.txt.' }
}
# A local mirror prevents recursively importing the host project through the package root.
# Only these distribution directories enter the mirror; source remains at the repository root.
$mirror = Join-Path $project 'LocalPackages~/com.connectpiece.sumi-engine'
$marker = Join-Path $mirror '.sumi-managed-mirror'
foreach ($candidate in @($project, (Join-Path $project 'LocalPackages~'), $mirror)) {
    if ((Test-Path -LiteralPath $candidate) -and ((Get-Item -LiteralPath $candidate).Attributes -band [IO.FileAttributes]::ReparsePoint)) {
        throw "Refusing a junction/symlink in the generated mirror path: $candidate"
    }
}
if ((Test-Path -LiteralPath $mirror) -and !(Test-Path -LiteralPath $marker)) { throw 'Unmanaged package mirror exists; refusing to overwrite it.' }
if (Test-Path -LiteralPath $mirror) {
    $resolvedMirror = (Resolve-Path -LiteralPath $mirror).Path
    $expectedMirror = [IO.Path]::GetFullPath((Join-Path $project 'LocalPackages~/com.connectpiece.sumi-engine'))
    if ($resolvedMirror -ne $expectedMirror) { throw 'Mirror path validation failed.' }
    # Delete only the explicitly marked, regenerable mirror, never the project or source.
    Remove-Item -LiteralPath $resolvedMirror -Recurse -Force
}
New-Item -ItemType Directory -Force -Path $mirror | Out-Null
Set-Content -LiteralPath $marker -Value 'Generated by Setup-UnitySandbox.ps1. Edit repository source, not this mirror.'
foreach ($entry in @('package.json', 'Runtime', 'Editor', 'Tests', 'Documentation~', 'LICENSE', 'README.md')) {
    $source = Join-Path $repo $entry
    if (Test-Path -LiteralPath $source) { Copy-Item -LiteralPath $source -Destination $mirror -Recurse }
    if (Test-Path -LiteralPath "$source.meta") { Copy-Item -LiteralPath "$source.meta" -Destination $mirror }
}
$manifestPath = Join-Path $project 'Packages/manifest.json'
$manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
$manifest.dependencies | Add-Member -NotePropertyName 'com.connectpiece.sumi-engine' -NotePropertyValue 'file:../LocalPackages~/com.connectpiece.sumi-engine' -Force
if (!$manifest.dependencies.PSObject.Properties['com.unity.test-framework']) {
    $testPackage = Join-Path (Split-Path -Parent $editor) 'Data/Resources/PackageManager/BuiltInPackages/com.unity.test-framework/package.json'
    if (!(Test-Path -LiteralPath $testPackage)) { throw 'Cannot determine bundled Test Framework version. Install it through Package Manager, then rerun.' }
    $testVersion = (Get-Content -LiteralPath $testPackage -Raw | ConvertFrom-Json).version
    $manifest.dependencies | Add-Member -NotePropertyName 'com.unity.test-framework' -NotePropertyValue $testVersion
}
$testables = @()
if ($manifest.PSObject.Properties['testables']) { $testables = @($manifest.testables) }
$manifest | Add-Member -NotePropertyName 'testables' -NotePropertyValue @($testables + 'com.connectpiece.sumi-engine' | Select-Object -Unique) -Force
# Keep an exact original manifest for recovery, without replacing previous backups.
if (!(Test-Path -LiteralPath "$manifestPath.sumi-backup")) { Copy-Item -LiteralPath $manifestPath -Destination "$manifestPath.sumi-backup" }
[IO.File]::WriteAllText($manifestPath, ($manifest | ConvertTo-Json -Depth 30), (New-Object Text.UTF8Encoding($false)))
Invoke-Unity @('-batchmode', '-nographics', '-quit', '-projectPath', "`"$project`"", '-executeMethod', 'ConnectPiece.SumiEngine.Editor.SumiLabMenu.GenerateSampleScenes', '-logFile', "`"$(Join-Path $logs 'unity-setup.log')`"")
foreach ($scene in @('BrushLab', 'BranchGrowth')) {
    if (!(Test-Path -LiteralPath (Join-Path $project "Assets/BrushLab/Scenes/$scene.unity"))) { throw "Scene generation missing: $scene" }
}
Write-Host "Setup completed with $exactVersion. Run EditMode tests and manual QA separately. Source changes require rerunning this script with Unity closed."

